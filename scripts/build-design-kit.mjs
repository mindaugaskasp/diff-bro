// The app's own styles, unscoped for canvas mockups; rerun after a style change.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const STYLES = 'src/renderer/src/styles'
const COMPONENT_STYLES = 'src/renderer/src/components/styles'
const COMPONENTS = [
  'SidebarRail',
  'SidebarSearch',
  'SectionHeader',
  'SnippetRow',
  'SnippetRowMeta',
  'DiffTabBar'
]
const OUT = 'design/components/app.css'

const read = (path) => readFileSync(path, 'utf8')

// A theme is keyed on <html> in the app; on a canvas it is any `.dk` container.
const rootToKit = (css) => css.replace(/:root/g, '.dk')
const unscope = (css) => css.replace(/:deep\(([^)]*)\)/g, '$1')
const bodyFont = read(join(STYLES, 'base.css')).match(/font-family:\s*([^;]+);/)[1]
const noticeRule = read(join(COMPONENT_STYLES, 'App.css')).match(/\.notice \{[^}]*\}/)[0]

const parts = [
  `/* Generated by scripts/build-design-kit.mjs from the app's styles. Do not edit. */`,
  rootToKit(read(join(STYLES, 'tokens.css'))),
  rootToKit(read(join(STYLES, 'themes.css'))),
  `.dk { background: var(--bg-canvas); color: var(--text); font-family: ${bodyFont}; font-size: 14px; }`,
  `.dk *, .dk *::before, .dk *::after { box-sizing: border-box; }`,
  read(join(STYLES, 'ui.css')),
  ...COMPONENTS.map((name) => unscope(read(join(COMPONENT_STYLES, `${name}.css`)))),
  noticeRule
]

writeFileSync(OUT, `${parts.join('\n\n')}\n`)
console.log(`wrote ${OUT}`)
