// Generate the Homebrew cask for Diff Bro's macOS build.
//
//   node scripts/gen-homebrew-cask.mjs [version] [--dmg <path>]
//
// version    defaults to package.json's version.
// --dmg      hash a local DMG (e.g. dist/diff-bro-v0.1.8.dmg after a build);
//            otherwise the script downloads the tagged release asset and hashes
//            that, so the sha256 matches exactly what users will download.
//
// The result is written to packaging/homebrew/diff-bro.rb. Copy that file into
// your Homebrew tap (a repo named `homebrew-<tap>`, e.g. Casks/diff-bro.rb) and
// push — see docs/packaging.md. A cask is the only per-release step Homebrew
// needs; the download URL is the tagged GitHub release asset.
import { createHash } from 'crypto'
import { readFile, writeFile } from 'fs/promises'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const REPO = 'mindaugaskasp/diff-bro'

// Must match `mac.artifactName` in electron-builder.yml. The DMG filename
// carries the version, so this is a function of it rather than a constant —
// and the cask interpolates Homebrew's own `version` into the URL, so the
// literal `#{version}` below is deliberate, not a template hole.
const asset = (version) => `diff-bro-v${version}.dmg`
const ASSET_TEMPLATE = 'diff-bro-v#{version}.dmg'

// Mirrors the packaged app's Info.plist LSMinimumSystemVersion, which Electron
// sets — bump these together when the Electron major changes, or `brew audit`
// fails with "cask should declare a minimum macOS version".
const ELECTRON_MAJOR = 39
const MIN_MACOS = '12.0'
const MIN_MACOS_SYMBOL = 'monterey'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

async function main() {
  const args = process.argv.slice(2)
  const dmgFlag = args.indexOf('--dmg')
  const localDmg = dmgFlag !== -1 ? args[dmgFlag + 1] : null
  const version =
    args.find((a) => !a.startsWith('--') && a !== localDmg) ??
    JSON.parse(await readFile(join(root, 'package.json'), 'utf8')).version

  const url = `https://github.com/${REPO}/releases/download/v${version}/${asset(version)}`

  let bytes
  if (localDmg) {
    bytes = await readFile(localDmg)
  } else {
    process.stderr.write(`Downloading ${url} to compute sha256…\n`)
    const res = await fetch(url)
    if (!res.ok) throw new Error(`Could not fetch ${url} (HTTP ${res.status}). Is v${version} released?`)
    bytes = Buffer.from(await res.arrayBuffer())
  }
  const sha256 = createHash('sha256').update(bytes).digest('hex')

  const cask = `# Generated by scripts/gen-homebrew-cask.mjs — do not edit by hand.
# Regenerate with \`make brew-cask\`; CI republishes it on every release.
cask "diff-bro" do
  version "${version}"
  sha256 "${sha256}"

  url "https://github.com/${REPO}/releases/download/v#{version}/${ASSET_TEMPLATE}"
  name "Diff Bro"
  desc "Offline-only desktop diff viewer"
  homepage "https://github.com/${REPO}"

  # The DMG carries an arm64-only build, and Electron ${ELECTRON_MAJOR} sets
  # LSMinimumSystemVersion ${MIN_MACOS}. Declared so \`brew install\` refuses up
  # front on an unsupported Mac instead of staging an app that cannot run.
  # A bare macOS symbol is Homebrew's ">= that version" form.
  depends_on arch: :arm64
  depends_on macos: :${MIN_MACOS_SYMBOL}

  app "Diff Bro.app"

  # Saved diffs, the identity keypair and window state live outside the app
  # bundle, so a plain uninstall leaves them behind. \`brew uninstall --zap\`
  # is the documented way to remove them too.
  zap trash: [
    "~/Library/Application Support/diffbro",
    "~/Library/Preferences/com.mindaugas.diffbro.plist",
    "~/Library/Saved Application State/com.mindaugas.diffbro.savedState",
  ]

  # ALPHA build: not signed or notarized (see DEVELOPMENT_PLAN.md Phase 3), so
  # macOS quarantines it and Gatekeeper reports it "damaged". We clear the
  # quarantine flag in postflight so \`brew install\` just works. This bypasses
  # Gatekeeper's check on THIS app — an accepted trade only because Homebrew has
  # already verified the download against the pinned sha256 above, and the
  # caveat below tells users plainly what they're installing. \`must_succeed:
  # false\` keeps a no-op strip (flag already absent) from failing the install.
  postflight do
    system_command "/usr/bin/xattr",
                   args: ["-dr", "com.apple.quarantine", "#{appdir}/Diff Bro.app"],
                   must_succeed: false
  end

  caveats <<~EOS
    ⚠️  ALPHA / development build — NOT signed or notarized by Apple.

    On install, Diff Bro's Gatekeeper quarantine flag is cleared automatically
    so the app will open. That means macOS does NOT vet this build for you —
    only install it if you trust this source. Expect rough edges and breaking
    changes between releases.
  EOS
end
`

  const out = join(root, 'packaging', 'homebrew', 'diff-bro.rb')
  await writeFile(out, cask)
  process.stderr.write(`Wrote ${out}\n  version ${version}\n  sha256  ${sha256}\n`)
}

main().catch((err) => {
  process.stderr.write(`${err.message}\n`)
  process.exit(1)
})
